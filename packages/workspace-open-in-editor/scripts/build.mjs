/**
 * Build the browser half into the DeepSeek Harness module-loader format.
 *
 * The web shell evaluates every client plugin as
 *
 *   window.__ModuleLoader__.load({ id, factory: (require) => { ... } })
 *
 * `require` answers the shell's frozen platform-module table, so React (and any
 * `@deepseek-ai/*` package declared in `dsh.client.inject`) must stay external
 * instead of being duplicated inside the bundle. Everything else is inlined.
 *
 * Usage:
 *   node scripts/build.mjs            # one production build
 *   node scripts/build.mjs --watch    # rebuild on source changes
 */
import { context } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(ROOT, 'lib/client.js')
const TEMP = resolve(ROOT, 'lib/.client.esbuild.cjs')
const WATCH = process.argv.includes('--watch')

const manifest = JSON.parse(await readFile(resolve(ROOT, 'package.json'), 'utf8'))
const ID = manifest.name

const BANNER = `/**
 * ${ID} — browser half.
 * Generated by scripts/build.mjs; edit src/client/** instead.
 */
window.__ModuleLoader__.load({ id: ${JSON.stringify(ID)}, factory: (require) => {
var module = { exports: {} }; var exports = module.exports;
Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
`
const FOOTER = `
return module.exports; } });
`

/** Wrap esbuild's CJS output in the harness loader envelope. */
const moduleLoaderWrapper = {
  name: 'dsh-module-loader-wrapper',
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length > 0) return
      const body = await readFile(TEMP, 'utf8')
      await writeFile(OUT, BANNER + body + FOOTER)
      await rm(TEMP, { force: true })
      console.log(`[${ID}] wrote ${OUT.slice(ROOT.length + 1)}`)
    })
  },
}

const options = {
  entryPoints: [resolve(ROOT, 'src/client/index.js')],
  outfile: TEMP,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  // Platform module table entries: never inline a second React runtime.
  external: ['react', 'react/jsx-runtime', 'react-dom'],
  define: {
    'process.env.NODE_ENV': '"production"',
  },
  sourcemap: false,
  legalComments: 'none',
  minify: false,
  logLevel: 'info',
  plugins: [moduleLoaderWrapper],
}

await mkdir(resolve(ROOT, 'lib'), { recursive: true })

if (WATCH) {
  const ctx = await context(options)
  await ctx.watch()
  console.log(`[${ID}] watching src/client/**`)
} else {
  const ctx = await context(options)
  await ctx.rebuild()
  await ctx.dispose()
}
